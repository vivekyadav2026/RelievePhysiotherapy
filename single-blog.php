            <h2 class="text-2xl font-bold text-gray-900 mt-10 mb-4">1. The Chin Tuck</h2>
            <p class="mb-6">
                This exercise strengthens the neck muscles and helps reverse tech neck.
            </p>
            <ul class="list-disc pl-6 mb-8 space-y-2">
                <li>Sit up straight and look straight ahead.</li>
                <li>Place a finger on your chin.</li>
                <li>Without moving your finger, pull your chin and head straight back until a good stretch is felt at the base of the head and top of the neck.</li>
                <li>Hold for 5 seconds. Repeat 10 times.</li>
            </ul>

            <h2 class="text-2xl font-bold text-gray-900 mt-10 mb-4">2. Scapular Retractions</h2>
            <p class="mb-6">
                Perfect for waking up the muscles between your shoulder blades that get stretched out when you slump.
            </p>
            <ul class="list-disc pl-6 mb-8 space-y-2">
                <li>Sit up tall and relax your shoulders down.</li>
                <li>Squeeze your shoulder blades together as if you are trying to hold a pencil between them.</li>
                <li>Hold the squeeze for 10 seconds.</li>
                <li>Release and repeat 5 times.</li>
            </ul>
            
